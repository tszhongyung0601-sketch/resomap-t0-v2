/**
 * Demo merchant supply.
 *
 * Three rules, and they are the same three the rest of this dataset keeps:
 *
 *  1. **Coordinates are real.** Every shop sits on a street that exists, within
 *     a few hundred metres of the POI it is meant to be "near", so the distance
 *     the card prints is measured rather than typed. `lib/nearby.ts` derives it
 *     from these numbers and nothing else.
 *  2. **Nothing here is a real business.** The names are invented. Attaching a
 *     made-up promotion and a made-up rating to a shop that actually exists is
 *     the one thing in this whole demo that could cost somebody real money.
 *  3. **Paying is not the same as being approved.** `isPaid` and `reviewStatus`
 *     are separate fields, and the 推薦夥伴 mark needs both — see
 *     `isVerifiedPartner` in lib/nearby.ts. Two records below are deliberately
 *     not eligible, so the rule is visible in the product rather than only in
 *     the code.
 *
 * Contact: `lineUrl` and `whatsappUrl` are the apps' own generic entry points.
 * They genuinely open, and they target nobody — a plausible-looking LINE id or
 * phone number in demo data is a stranger's phone ringing. `phone` and
 * `bookingUrl` are left unset on purpose, which is what exercises the other
 * half of lib/contact.ts.
 */

