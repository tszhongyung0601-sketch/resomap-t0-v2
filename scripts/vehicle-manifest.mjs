import { readdir, readFile, writeFile } from "node:fs/promises";

/**
 * Rewrite `src/data/vehicles.ts` from what is actually in public/vehicles/.
 *
 * A reading of the directory, never a list somebody maintains. The portrait
 * manifest next door explains why in one line: a hand-kept list drifts, and
 * every entry that drifts is a broken image on a card.
 */
export async function writeVehicleManifest({
  out = "public/vehicles",
  rentals = "src/data/carRentals.ts",
  manifest = "src/data/vehicles.ts",
} = {}) {
  const known = new Set(
    [...(await readFile(rentals, "utf8")).matchAll(/\n {4}id: "(r-[^"]+)"/g)].map((m) => m[1]),
  );

  let files = [];
  try {
    files = await readdir(out);
  } catch {
    /* nothing fetched yet */
  }

  const built = files
    .filter((f) => f.endsWith("-card.webp"))
    .map((f) => f.replace(/-card\.webp$/, ""))
    .filter((id) => known.has(id))
    .sort();

  await writeFile(
    manifest,
    `/**
 * Which hire counters have a vehicle photograph on disk.
 *
 * GENERATED by \`node scripts/fetch-stock-vehicles.mjs\`. Do not hand-edit: an id
 * in here without a file behind it is a broken image on a card.
 *
 * A manifest rather than a field on each \`CarRental\`: the record describes the
 * counter, and whether a picture has been fetched yet is a fact about the
 * repository. It also means the app never requests a file that is not there,
 * which is the difference between a designed fallback and a 404.
 *
 * None of these is a photograph of the counter it sits on — they are stock
 * photographs of the class of car the record offers. That is why \`VehiclePhoto\`
 * puts a mark on the image itself rather than a line at the foot of the page.
 */
export const VEHICLE_IDS: ReadonlySet<string> = new Set([
${built.map((id) => `  "${id}",`).join("\n")}
]);

export const hasVehiclePhoto = (rentalId: string) => VEHICLE_IDS.has(rentalId);
`,
    "utf8",
  );

  return { built, missing: [...known].filter((id) => !built.includes(id)).sort(), known };
}
